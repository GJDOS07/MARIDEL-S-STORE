"use strict";
// Integration tests for the owner order list, run against a REAL isolated
// PostgreSQL (PGlite/WASM, in-memory). The owner dashboard renders order.items,
// so every order the list returns must carry its item rows.
//
// Production is never contacted: every test creates its own in-memory database.

const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const { promisify } = require("node:util");
const express = require("express");

const { PGlite } = require("@electric-sql/pglite");
const { createOrderRouter } = require("./order-routes");
const { createApiErrorHandler } = require("./api-error-handler");

const scrypt = promisify(crypto.scrypt);
const root = __dirname;
const MIGRATION = fs.readFileSync(path.join(root, "owner-account-and-products.sql"), "utf8");
const ORDER_MIGRATION = fs.readFileSync(path.join(root, "production-order-system.sql"), "utf8");

const OWNER_ORIGIN = "https://store.example";
const OWNER_PASSWORD = "synthetic-owner-password-123";

// The same legacy schema the owner endpoint integration tests use, mirroring
// the products/orders/order_items tables before either migration runs.
const LEGACY_SCHEMA = `
CREATE TABLE products (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR NOT NULL,
	category VARCHAR,
	price NUMERIC NOT NULL,
	original_price NUMERIC,
	image TEXT,
	description TEXT,
	stock INTEGER DEFAULT 0,
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE orders (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	customer_id INTEGER,
	subtotal NUMERIC NOT NULL,
	discount NUMERIC DEFAULT 0,
	shipping_fee NUMERIC DEFAULT 0,
	total NUMERIC NOT NULL,
	status VARCHAR DEFAULT 'Pending',
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	customer_name TEXT,
	customer_contact TEXT,
	customer_email TEXT,
	pickup_type TEXT,
	pickup_date DATE,
	pickup_time TEXT,
	requested_pickup_time TEXT,
	total_amount NUMERIC,
	customer_access_token TEXT,
	idempotency_key TEXT,
	order_number TEXT,
	tracking_token_hash CHAR(64),
	idempotency_fingerprint CHAR(64),
	cancellation_reason TEXT
);

CREATE TABLE order_items (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	order_id INTEGER REFERENCES orders(id) ON DELETE CASCADE,
	product_id INTEGER,
	quantity INTEGER NOT NULL,
	price NUMERIC NOT NULL,
	product_name TEXT,
	unit_price NUMERIC,
	subtotal NUMERIC
);

CREATE TABLE owner_sessions (
	session_hash CHAR(64) PRIMARY KEY CHECK (session_hash ~ '^[a-f0-9]{64}$'),
	expires_at TIMESTAMPTZ NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS owner_sessions_expires_at_idx ON public.owner_sessions (expires_at);

CREATE TABLE owner_login_attempts (
	client_key_hash CHAR(64) PRIMARY KEY CHECK (client_key_hash ~ '^[a-f0-9]{64}$'),
	window_started_at TIMESTAMPTZ NOT NULL,
	attempt_count INTEGER NOT NULL CHECK (attempt_count BETWEEN 1 AND 1000000)
);
`;

async function createDatabase() {
	const db = await PGlite.create();
	await db.exec(LEGACY_SCHEMA);

	// A small catalog is enough for the item rows. Ids 73 and 74 are the
	// historical products the shared owner fixture uses.
	for (let index = 1; index <= 18; index += 1) {
		const id = index === 1 ? 73 : index === 2 ? 74 : index;
		const name = id === 73
			? "Pocari Sweat 330ml"
			: id === 74 ? "Jufran Banana Sauce 560g" : `Legacy Product ${id}`;
		await db.query(
			"INSERT INTO products (id, name, category, price, description, stock) VALUES ($1,$2,$3,$4,$5,$6)",
			[
				id,
				name,
				id % 2 === 0 ? "Sauces" : "Drinks",
				id === 73 ? "55.00" : id === 74 ? "2.50" : `${id}.50`,
				id === 73 ? "Ion supply drink." : id === 74 ? "Banana sauce." : `Description ${id}.`,
				id,
			],
		);
	}

	await db.query(
		`INSERT INTO orders (id, customer_id, subtotal, total, status, customer_name, customer_contact,
			pickup_type, pickup_date, pickup_time, requested_pickup_time, total_amount, customer_access_token, idempotency_key, order_number)
		 VALUES (1, NULL, 110.00, 110.00, 'Pending', 'Legacy Customer', '0400000000',
			'SCHEDULED', '2026-03-10', '13:30', '13:30', 110.00,
			'legacy-credential-0000000000000000000000000000000001', $1, 'MS-1')`,
		["9".repeat(64)],
	);
	await db.query(
		"INSERT INTO order_items (order_id, product_id, quantity, price, product_name, unit_price, subtotal) VALUES ($1,$2,$3,$4,$5,$6,$7)",
		[1, 73, 2, "55.00", "Pocari Sweat 330ml", "55.00", "110.00"],
	);

	await db.exec(ORDER_MIGRATION);
	await db.exec(MIGRATION);

	// The fixture inserts explicit product/order ids, and GENERATED BY DEFAULT AS
	// IDENTITY does not advance the sequences on its own, so a later create would
	// collide with id 1. Advance the sequences the same way production would have.
	for (const table of ["products", "orders", "order_items"]) {
		await db.query(
			"SELECT setval(pg_get_serial_sequence($1, 'id'), GREATEST((SELECT COALESCE(MAX(id), 0) FROM public." + table + "), 1), true)",
			["public." + table],
		);
	}

	// Every test logs in from 127.0.0.1, so each test needs a clean rate-limit
	// budget exactly as a separate deployment would have.
	await db.query("DELETE FROM owner_login_attempts");

	return db;
}

function createRealPool(db) {
	// PGlite returns rows: [] for statements without RETURNING and reports the
	// affected count separately, so rowCount must come from affectedRows when
	// present. A DELETE that matched rows otherwise looks like a 404.
	const shape = (result) => ({
		rows: result.rows,
		rowCount: typeof result.affectedRows === "number" && result.rows.length === 0
			? result.affectedRows
			: result.rows.length,
		fields: result.fields,
	});
	return {
		async query(sql, params = []) {
			const result = await db.query(sql, params);
			return shape(result);
		},
		async connect() {
			return {
				async query(sql, params = []) {
					const result = await db.query(sql, params);
					return shape(result);
				},
				release() {},
			};
		},
	};
}

async function startServer(db, options = {}) {
	const app = express();
	app.use(express.json({ limit: "1mb" }));
	app.use("/api", createOrderRouter(createRealPool(db), {
		allowedOrigins: [OWNER_ORIGIN],
		secureCookies: false,
		...options,
	}));
	app.use(createApiErrorHandler({ error() {} }));
	const server = app.listen(0, "127.0.0.1");
	await new Promise(resolve => server.once("listening", resolve));
	return { url: `http://127.0.0.1:${server.address().port}`, close: () => new Promise((r, e) => server.close(err => (err ? e(err) : r()))) };
}

async function makeCredentials() {
	const salt = crypto.randomBytes(16);
	const digest = await scrypt(OWNER_PASSWORD, salt, 64);
	return {
		ownerPasswordHash: `scrypt$${salt.toString("hex")}$${digest.toString("hex")}`,
		sessionSecret: crypto.randomBytes(32).toString("base64url"),
	};
}

async function attemptLogin(server, password) {
	const csrf = await fetch(`${server.url}/api/owner/csrf`, { headers: { Origin: OWNER_ORIGIN } });
	const csrfBody = await csrf.json();
	const jar = csrf.headers.getSetCookie().map(c => c.split(";")[0]);
	return fetch(`${server.url}/api/owner/login`, {
		method: "POST",
		headers: {
			Origin: OWNER_ORIGIN,
			"Content-Type": "application/json",
			Cookie: jar.join("; "),
			"X-CSRF-Token": csrfBody.csrf_token,
		},
		body: JSON.stringify({ password }),
	});
}

async function login(server, password = OWNER_PASSWORD) {
	const response = await attemptLogin(server, password);
	assert.equal(response.status, 200, "login must succeed");
	const body = await response.json();
	const cookieJar = response.headers.getSetCookie().map(c => c.split(";")[0]);
	return { cookies: cookieJar.join("; "), csrfToken: body.csrf_token };
}

function ownerRequest(server, session, method, url, body) {
	return fetch(`${server.url}${url}`, {
		method,
		headers: {
			Origin: OWNER_ORIGIN,
			"Content-Type": "application/json",
			Cookie: session.cookies,
			"X-CSRF-Token": session.csrfToken,
		},
		body: body === undefined ? undefined : JSON.stringify(body),
	});
}

async function insertOrder(db, { customerName, status = "Pending", total = "0.00" }) {
	const result = await db.query(
		`INSERT INTO orders (customer_name, customer_contact, subtotal, total, status,
			pickup_type, pickup_date, pickup_time, requested_pickup_time)
		 VALUES ($1, $2, $3, $4, $5, 'SCHEDULED', '2099-06-15', '13:30', '13:30')
		 RETURNING id`,
		[customerName, "0400000000", total, total, status],
	);
	return result.rows[0].id;
}

async function insertItem(db, { orderId, productId, quantity, price, productName, unitPrice, subtotal }) {
	await db.query(
		`INSERT INTO order_items (order_id, product_id, quantity, price, product_name, unit_price, subtotal)
		 VALUES ($1,$2,$3,$4,$5,$6,$7)`,
		[orderId, productId, quantity, price, productName, unitPrice, subtotal],
	);
}

test("owner order list attaches every order's items in a single lookup", async t => {
	const db = await createDatabase();
	t.after(() => db.close());
	const server = await startServer(db, await makeCredentials());
	t.after(() => server.close());
	const session = await login(server);

	const twoItemOrder = await insertOrder(db, {
		customerName: "Two Item Customer",
		status: "Confirmed",
		total: "112.50",
	});
	await insertItem(db, {
		orderId: twoItemOrder,
		productId: 73,
		quantity: 2,
		price: "55.00",
		productName: "Pocari Sweat 330ml",
		unitPrice: "55.00",
		subtotal: "110.00",
	});
	await insertItem(db, {
		orderId: twoItemOrder,
		productId: 74,
		quantity: 1,
		price: "2.50",
		productName: "Jufran Banana Sauce 560g",
		unitPrice: "2.50",
		subtotal: "2.50",
	});

	const oneItemOrder = await insertOrder(db, {
		customerName: "One Item Customer",
		status: "Pending",
		total: "7.50",
	});
	await insertItem(db, {
		orderId: oneItemOrder,
		productId: 74,
		quantity: 3,
		price: "2.50",
		productName: "Jufran Banana Sauce 560g",
		unitPrice: "2.50",
		subtotal: "7.50",
	});

	const emptyOrder = await insertOrder(db, {
		customerName: "No Item Customer",
		status: "Cancelled",
		total: "0.00",
	});

	const response = await ownerRequest(server, session, "GET", "/api/owner/orders");
	assert.equal(response.status, 200);
	assert.equal(response.headers.get("cache-control"), "no-store");
	const orders = await response.json();

	const twoItemOrderBody = orders.find(order => order.customer_name === "Two Item Customer");
	assert.ok(twoItemOrderBody, "the order with two products must be listed");
	assert.deepEqual(twoItemOrderBody.items, [
		{ product_name: "Pocari Sweat 330ml", unit_price: "55.00", quantity: 2, subtotal: "110.00" },
		{ product_name: "Jufran Banana Sauce 560g", unit_price: "2.50", quantity: 1, subtotal: "2.50" },
	]);

	const oneItemOrderBody = orders.find(order => order.customer_name === "One Item Customer");
	assert.ok(oneItemOrderBody, "the order with one product must be listed");
	assert.deepEqual(oneItemOrderBody.items, [
		{ product_name: "Jufran Banana Sauce 560g", unit_price: "2.50", quantity: 3, subtotal: "7.50" },
	]);

	const emptyOrderBody = orders.find(order => order.customer_name === "No Item Customer");
	assert.ok(emptyOrderBody, "the order without products must still be listed");
	assert.deepEqual(emptyOrderBody.items, []);
	assert.ok(Array.isArray(emptyOrderBody.items));
	assert.notEqual(emptyOrderBody.id, undefined);
	assert.equal(emptyOrderBody.order_number, `MS-${emptyOrderBody.id}`);

	const filteredResponse = await ownerRequest(server, session, "GET", "/api/owner/orders?status=Confirmed");
	assert.equal(filteredResponse.status, 200);
	const filteredOrders = await filteredResponse.json();
	assert.equal(filteredOrders.length, 1, "the status filter must still return only matching orders");
	assert.equal(filteredOrders[0].customer_name, "Two Item Customer");
	assert.deepEqual(filteredOrders[0].items, twoItemOrderBody.items);
	assert.notEqual(filteredOrders[0].order_number, undefined);

	// An empty page still answers with an array and never runs the item lookup.
	const emptyPage = await ownerRequest(server, session, "GET", "/api/owner/orders?offset=100");
	assert.equal(emptyPage.status, 200);
	assert.deepEqual(await emptyPage.json(), []);
});
