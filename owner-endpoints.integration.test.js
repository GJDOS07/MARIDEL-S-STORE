test("the deployed CORS policy allows every method the owner dashboard uses", async t => {
	// server.js constructs the app with its own CORS options, so read the real
	// file rather than assuming: a method missing from the list makes the
	// browser preflight fail, which no in-process request can catch.
	const fs = require("node:fs");
	const source = fs.readFileSync(path.join(root, "server.js"), "utf8");
	const match = /methods:\s*\[([^\]]+)\]/.exec(source);
	assert.ok(match, "server.js must configure the CORS methods list");
	const methods = match[1].split(",").map(entry => entry.trim().replace(/"/g, ""));
	for (const required of ["GET", "POST", "PATCH", "DELETE", "OPTIONS"]) {
		assert.ok(methods.includes(required), `CORS must allow ${required}`);
	}

	// Every method the dashboard actually issues must be one the server allows.
	const dashboard = fs.readFileSync(path.join(root, "owner-dashboard.js"), "utf8");
	const used = [...dashboard.matchAll(/method:\s*"([A-Z]+)"/g)].map(found => found[1]);
	assert.ok(used.length > 0, "the dashboard must issue some methods");
	for (const method of used) {
		assert.ok(methods.includes(method), `dashboard ${method} must be allowed by CORS`);
	}
	assert.ok(used.includes("PATCH") && used.includes("DELETE"),
		"the dashboard must use PATCH and DELETE for product edit and delete");
});

