// --- migration rerun safety --------------------------------------------------
//
// The catalog size is expected to change: products are added and removed
// through the owner dashboard. A valid migration rerun must never fail merely
// because the count moved away from the 18 rows that existed when it was
// written.

const OWNER_TABLES = `
CREATE TABLE owner_sessions (
	session_hash CHAR(64) PRIMARY KEY CHECK (session_hash ~ '^[a-f0-9]{64}$'),
	expires_at TIMESTAMPTZ NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE owner_login_attempts (
	client_key_hash CHAR(64) PRIMARY KEY CHECK (client_key_hash ~ '^[a-f0-9]{64}$'),
	window_started_at TIMESTAMPTZ NOT NULL,
	attempt_count INTEGER NOT NULL CHECK (attempt_count BETWEEN 1 AND 1000000)
);
`;

const PRODUCTS_TABLE = `
CREATE TABLE products (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR NOT NULL,
	category VARCHAR,
	price NUMERIC NOT NULL,
	original_price NUMERIC,
	image TEXT,
	description TEXT,
	stock INTEGER DEFAULT 0,
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
`;

async function catalogDatabase(productCount) {
	const db = await PGlite.create();
	await db.exec(PRODUCTS_TABLE);
	await db.exec(OWNER_TABLES);
	for (let index = 1; index <= productCount; index += 1) {
		await db.query(
			"INSERT INTO products (name, category, price, description, stock) VALUES ($1,$2,$3,$4,$5)",
			[`Product ${index}`, index % 2 === 0 ? "Sauces" : "Drinks", `${index}.50`, `Description ${index}.`, index],
		);
	}
	return db;
}

const appliedObjectCount = db => db.query(
	`SELECT
		(SELECT count(*)::int FROM information_schema.tables WHERE table_schema='public'
			AND table_name IN ('owner_credentials','owner_reset_tokens','owner_contact')) AS tables_added,
		(SELECT count(*)::int FROM information_schema.columns WHERE table_schema='public'
			AND table_name='products' AND column_name='is_published') AS column_added`,
);

test("the migration succeeds on a catalog that is not exactly 18 products", async t => {
	// A small catalog (5) and a larger one (20) must both apply.
	for (const count of [0, 1, 5, 17, 20, 40]) {
		const db = await catalogDatabase(count);
		t.after(() => db.close());
		await db.exec(MIGRATION);
		const state = await appliedObjectCount(db);
		assert.equal(state.rows[0].tables_added, 3, `three tables added with ${count} products`);
		assert.equal(state.rows[0].column_added, 1, `is_published added with ${count} products`);
		// Default/backfill: every pre-existing product stays published, and the
		// column carries the NOT NULL DEFAULT true shape the backfill relies on.
		const hidden = await db.query("SELECT count(*)::int AS n FROM products WHERE NOT is_published");
		assert.equal(hidden.rows[0].n, 0, `no product is hidden by the backfill with ${count} products`);
		const shape = await db.query(
			"SELECT column_default, is_nullable FROM information_schema.columns WHERE table_schema='public' AND table_name='products' AND column_name='is_published'",
		);
		assert.equal(shape.rows[0].column_default, "true", `backfill default with ${count} products`);
		assert.equal(shape.rows[0].is_nullable, "NO", `column must stay NOT NULL with ${count} products`);
	}
});

test("the migration refuses a product with a NULL visibility value", async t => {
	const db = await catalogDatabase(2);
	t.after(() => db.close());
	await db.exec(MIGRATION);
	// A NULL can only be produced by a write that bypassed the default, which is
	// a real defect and must be caught on a rerun, not silently accepted.
	// The migration is one transaction, so a failure leaves it aborted and the
	// session must ROLLBACK before anything else can run: this is the normal
	// fail-closed behaviour and the reason it is safe to apply in one batch.
	await db.query("ALTER TABLE products ALTER COLUMN is_published DROP NOT NULL");
	await db.query("UPDATE products SET is_published = NULL WHERE id = 1");
	await assert.rejects(() => db.exec(MIGRATION), /Verification failed/i);
	await db.exec("ROLLBACK");
	assert.equal(
		(await db.query("SELECT count(*)::int AS n FROM products")).rows[0].n, 2,
		"the rejected migration must leave the catalog untouched",
	);
});

test("the migration can be re-run after the owner adds and removes products", async t => {
	const db = await catalogDatabase(18);
	t.after(() => db.close());
	await db.exec(MIGRATION);

	// Grow the catalog, then shrink it, then re-run.
	await db.query("INSERT INTO products (name, price, stock) VALUES ('New Product', 9.99, 5)");
	await db.query("INSERT INTO products (name, price, stock) VALUES ('Another Product', 4.00, 5)");
	await db.exec(MIGRATION);
	assert.equal((await db.query("SELECT count(*)::int AS n FROM products")).rows[0].n, 20, "products are preserved");

	await db.query("DELETE FROM products WHERE name IN ('New Product', 'Another Product', 'Product 1', 'Product 2')");
	await db.exec(MIGRATION);
	assert.equal((await db.query("SELECT count(*)::int AS n FROM products")).rows[0].n, 16, "products are preserved on the second rerun");

	// Products hidden before a rerun stay hidden; the rerun must not republish.
	await db.query("UPDATE products SET is_published = false WHERE id = 5");
	await db.exec(MIGRATION);
	const hidden = await db.query("SELECT count(*)::int AS n FROM products WHERE id = 5 AND NOT is_published");
	assert.equal(hidden.rows[0].n, 1, "a rerun must not republish a hidden product");
});

