test("delete cannot orphan order history even when an order arrives concurrently", async t => {
	const db = await createDatabase();
	t.after(() => db.close());
	const creds = await makeCredentials();
	const server = await startServer(db, creds);
	t.after(() => server.close());
	const session = await login(server);

	// Product 17 is unreferenced and deletable. An order item for it appearing
	// after the route's own pre-read but before the DELETE must still stop the
	// delete: the reference check and the DELETE are one statement.
	await db.query(
		"INSERT INTO order_items (order_id, product_id, quantity, price, product_name, unit_price, subtotal) VALUES ($1,$2,$3,$4,$5,$6,$7)",
		[1, 17, 1, "17.50", "Legacy Product 17", "17.50", "17.50"],
	);
	const refused = await ownerRequest(server, session, "DELETE", "/api/owner/products/17", { confirm: "DELETE" });
	assert.equal(refused.status, 409, "a newly referenced product must refuse to delete");
	const stillThere = await db.query("SELECT count(*)::int AS n FROM products WHERE id = 17");
	assert.equal(stillThere.rows[0].n, 1, "the product row must survive");
	const item = await db.query("SELECT count(*)::int AS n FROM order_items WHERE product_id = 17");
	assert.equal(item.rows[0].n, 1, "order history must not be orphaned");

	// A still-unreferenced product can be deleted normally.
	await db.query("DELETE FROM order_items WHERE product_id = 17");
	const allowed = await ownerRequest(server, session, "DELETE", "/api/owner/products/17", { confirm: "DELETE" });
	assert.equal(allowed.status, 200, "an unreferenced product can still be removed");
	assert.equal((await db.query("SELECT count(*)::int AS n FROM products WHERE id = 17")).rows[0].n, 0);

	// Deleting something already gone is a 404, not a silent success.
	const gone = await ownerRequest(server, session, "DELETE", "/api/owner/products/17", { confirm: "DELETE" });
	assert.equal(gone.status, 404);
});

