"use strict";
// The local sandbox database: schema, seed catalog, and migrations.
//
// WHY THIS EXISTS
//   server.js reads DATABASE_URL from the environment and opens a pg Pool. In
//   this workspace that variable points at the production database, so running
//   the backend locally would read and write production rows, and there was no
//   supported way to exercise the real server end to end without doing so.
//
//   This module builds an isolated, in-process PostgreSQL (PGlite) database that
//   applies the real migrations, seeds the same catalog the integration tests
//   use, and exposes it through the pool adapter. It is used only when
//   LOCAL_SANDBOX_DB is set, so production behaviour is untouched.
//
// WHAT IT DOES NOT DO
//   It never connects to anything: no network, no DATABASE_URL, no Neon. The
//   data it creates is synthetic and lives in memory (or on the local disk when
//   a data directory is configured), and it is discarded when the process ends.

const fs = require("node:fs");
const path = require("node:path");

// Legacy schema mirroring the production products/orders/order_items tables
// BEFORE either migration, plus the two owner tables the order migration adds.
// The two stock columns are included even though stock-migration.sql adds them
// later, so the sandbox models production after that migration is applied.
// Kept as one constant so the tests and the sandbox build the same database.
const LEGACY_SCHEMA = `
CREATE TABLE products (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR NOT NULL,
	category VARCHAR,
	price NUMERIC NOT NULL,
	original_price NUMERIC,
	image TEXT,
	description TEXT,
	stock INTEGER DEFAULT 0,
	low_stock_threshold INTEGER NOT NULL DEFAULT 5,
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE orders (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	customer_id INTEGER,
	subtotal NUMERIC NOT NULL,
	discount NUMERIC DEFAULT 0,
	shipping_fee NUMERIC DEFAULT 0,
	total NUMERIC NOT NULL,
	status VARCHAR DEFAULT 'Pending',
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	customer_name TEXT,
	customer_contact TEXT,
	customer_email TEXT,
	pickup_type TEXT,
	pickup_date DATE,
	pickup_time TEXT,
	requested_pickup_time TEXT,
	total_amount NUMERIC,
	customer_access_token TEXT,
	idempotency_key TEXT,
	order_number TEXT,
	tracking_token_hash CHAR(64),
	idempotency_fingerprint CHAR(64),
	cancellation_reason TEXT
);

CREATE TABLE order_items (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	order_id INTEGER REFERENCES orders(id) ON DELETE CASCADE,
	product_id INTEGER,
	quantity INTEGER NOT NULL,
	price NUMERIC NOT NULL,
	product_name TEXT,
	unit_price NUMERIC,
	subtotal NUMERIC
);

CREATE TABLE owner_sessions (
	session_hash CHAR(64) PRIMARY KEY CHECK (session_hash ~ '^[a-f0-9]{64}$'),
	expires_at TIMESTAMPTZ NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS owner_sessions_expires_at_idx ON public.owner_sessions (expires_at);

CREATE TABLE owner_login_attempts (
	client_key_hash CHAR(64) PRIMARY KEY CHECK (client_key_hash ~ '^[a-f0-9]{64}$'),
	window_started_at TIMESTAMPTZ NOT NULL,
	attempt_count INTEGER NOT NULL CHECK (attempt_count BETWEEN 1 AND 1000000)
);
`;

const MIGRATION_FILES = [
	"production-order-system.sql",
	"owner-account-and-products.sql",
];

function readSql(name) {
	return fs.readFileSync(path.join(__dirname, name), "utf8");
}

// Seeds the same catalog the integration tests use: 18 products with ids 73 and
// 74 reserved for the order-referenced and unreferenced cases, one historical
// order, and one order item. Identical to the test fixture, so behaviour seen in
// the sandbox is behaviour the tests assert.
async function seedCatalog(db) {
	for (let index = 1; index <= 18; index += 1) {
		const id = index === 1 ? 73 : index === 2 ? 74 : index;
		const name = id === 73
			? "Pocari Sweat 330ml"
			: id === 74 ? "Jufran Banana Sauce 560g" : `Legacy Product ${id}`;
		await db.query(
			"INSERT INTO products (id, name, category, price, description, stock) VALUES ($1,$2,$3,$4,$5,$6)",
			[
				id,
				name,
				id % 2 === 0 ? "Sauces" : "Drinks",
				id === 73 ? "55.00" : id === 74 ? "2.50" : `${id}.50`,
				id === 73 ? "Ion supply drink." : id === 74 ? "Banana sauce." : `Description ${id}.`,
				id,
			],
		);
	}

	await db.query(
		`INSERT INTO orders (id, customer_id, subtotal, total, status, customer_name, customer_contact,
			pickup_type, pickup_date, pickup_time, requested_pickup_time, total_amount, customer_access_token, idempotency_key, order_number)
		 VALUES (1, NULL, 110.00, 110.00, 'Pending', 'Legacy Customer', '0400000000',
			'SCHEDULED', '2026-03-10', '13:30', '13:30', 110.00,
			'legacy-credential-0000000000000000000000000000000001', $1, 'MS-1')`,
		["9".repeat(64)],
	);
	await db.query(
		"INSERT INTO order_items (order_id, product_id, quantity, price, product_name, unit_price, subtotal) VALUES ($1,$2,$3,$4,$5,$6,$7)",
		[1, 73, 2, "55.00", "Pocari Sweat 330ml", "55.00", "110.00"],
	);

	// The fixture inserts explicit ids, and GENERATED BY DEFAULT AS IDENTITY does
	// not advance the sequence on its own, so a create would collide with id 1.
	for (const table of ["products", "orders", "order_items"]) {
		await db.query(
			"SELECT setval(pg_get_serial_sequence($1, 'id'), GREATEST((SELECT COALESCE(MAX(id), 0) FROM public." + table + "), 1), true)",
			["public." + table],
		);
	}
}

module.exports = { LEGACY_SCHEMA, seedCatalog, MIGRATION_FILES, readSql };
