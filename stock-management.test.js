// The same legacy schema the other integration tests use, with the two stock
// columns stock-migration.sql adds (the sandbox models production after that
// file has been applied).
const LEGACY_SCHEMA = `
CREATE TABLE products (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR NOT NULL,
	category VARCHAR,
	price NUMERIC NOT NULL,
	original_price NUMERIC,
	image TEXT,
	description TEXT,
	stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
	low_stock_threshold INTEGER NOT NULL DEFAULT 5,
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE orders (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	customer_id INTEGER,
	subtotal NUMERIC NOT NULL,
	discount NUMERIC DEFAULT 0,
	shipping_fee NUMERIC DEFAULT 0,
	total NUMERIC NOT NULL,
	status VARCHAR DEFAULT 'Pending',
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	customer_name TEXT,
	customer_contact TEXT,
	customer_email TEXT,
	pickup_type TEXT,
	pickup_date DATE,
	pickup_time TEXT,
	requested_pickup_time TEXT,
	total_amount NUMERIC,
	customer_access_token TEXT,
	idempotency_key TEXT,
	idempotency_fingerprint CHAR(64),
	order_number TEXT,
	tracking_token_hash CHAR(64),
	cancellation_reason TEXT
);

CREATE TABLE order_items (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	order_id INTEGER REFERENCES orders(id) ON DELETE CASCADE,
	product_id INTEGER,
	quantity INTEGER NOT NULL,
	price NUMERIC NOT NULL,
	product_name TEXT,
	unit_price NUMERIC,
	subtotal NUMERIC
);

CREATE TABLE owner_sessions (
	session_hash CHAR(64) PRIMARY KEY CHECK (session_hash ~ '^[a-f0-9]{64}$'),
	expires_at TIMESTAMPTZ NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS owner_sessions_expires_at_idx ON public.owner_sessions (expires_at);

CREATE TABLE owner_login_attempts (
	client_key_hash CHAR(64) PRIMARY KEY CHECK (client_key_hash ~ '^[a-f0-9]{64}$'),
	window_started_at TIMESTAMPTZ NOT NULL,
	attempt_count INTEGER NOT NULL CHECK (attempt_count BETWEEN 1 AND 1000000)
);
`;

async function createDatabase() {
	const db = await PGlite.create();
	await db.exec(LEGACY_SCHEMA);

	await db.query(
		"INSERT INTO products (name, category, price, description, stock) VALUES ($1,$2,$3,$4,$5)",
		["Pocari Sweat 330ml", "Drinks", "2.50", "Ion supply drink.", 3],
	);
	await db.query(
		"INSERT INTO products (name, category, price, description, stock) VALUES ($1,$2,$3,$4,$5)",
		["Jufran Banana Sauce 560g", "Sauces", "5.50", "Banana sauce.", 0],
	);

	// Every test logs in from 127.0.0.1, so each test needs a clean rate-limit
	// budget exactly as a separate deployment would have.
	await db.query("DELETE FROM owner_login_attempts");

	return db;
}

function createRealPool(db) {
	// PGlite returns rows: [] for statements without RETURNING and reports the
	// affected count separately, so rowCount must come from affectedRows when
	// present.
	const shape = (result) => ({
		rows: result.rows,
		rowCount: typeof result.affectedRows === "number" && result.rows.length === 0
			? result.affectedRows
			: result.rows.length,
		fields: result.fields,
	});
	return {
		async query(sql, params = []) {
			const result = await db.query(sql, params);
			return shape(result);
		},
		async connect() {
			return {
				async query(sql, params = []) {
					const result = await db.query(sql, params);
					return shape(result);
				},
				release() {},
			};
		},
	};
}

async function startServer(db, options = {}) {
	const app = express();
	app.use(express.json({ limit: "1mb" }));
	app.use("/api", createOrderRouter(createRealPool(db), {
		allowedOrigins: [OWNER_ORIGIN],
		secureCookies: false,
		...options,
	}));
	app.use(createApiErrorHandler({ error() {} }));
	const server = app.listen(0, "127.0.0.1");
	await new Promise(resolve => server.once("listening", resolve));
	return { url: `http://127.0.0.1:${server.address().port}`, close: () => new Promise((r, e) => server.close(err => (err ? e(err) : r()))) };
}

async function makeCredentials() {
	const salt = crypto.randomBytes(16);
	const digest = await scrypt(OWNER_PASSWORD, salt, 64);
	return {
		ownerPasswordHash: `scrypt$${salt.toString("hex")}$${digest.toString("hex")}`,
		sessionSecret: crypto.randomBytes(32).toString("base64url"),
	};
}

async function login(server, password = OWNER_PASSWORD) {
	const csrf = await fetch(`${server.url}/api/owner/csrf`, { headers: { Origin: OWNER_ORIGIN } });
	const csrfBody = await csrf.json();
	const jar = csrf.headers.getSetCookie().map(c => c.split(";")[0]);
	const response = await fetch(`${server.url}/api/owner/login`, {
		method: "POST",
		headers: {
			Origin: OWNER_ORIGIN,
			"Content-Type": "application/json",
			Cookie: jar.join("; "),
			"X-CSRF-Token": csrfBody.csrf_token,
		},
		body: JSON.stringify({ password }),
	});
	assert.equal(response.status, 200, "login must succeed");
	const body = await response.json();
	const cookieJar = response.headers.getSetCookie().map(c => c.split(";")[0]);
	return { cookies: cookieJar.join("; "), csrfToken: body.csrf_token };
}

function ownerRequest(server, session, method, url, body) {
	return fetch(`${server.url}${url}`, {
		method,
		headers: {
			Origin: OWNER_ORIGIN,
			"Content-Type": "application/json",
			Cookie: session.cookies,
			"X-CSRF-Token": session.csrfToken,
		},
		body: body === undefined ? undefined : JSON.stringify(body),
	});
}

async function stockOf(db, productId) {
	const result = await db.query("SELECT stock::int AS stock FROM products WHERE id = $1", [productId]);
	return Number(result.rows[0].stock);
}

function checkoutBody() {
	return {
		customer_name: "Stock Test Customer",
		customer_contact: "0400000000",
		pickup_date: "2099-06-15",
		pickup_time: "13:30",
		items: [{ product_id: 1, quantity: 2 }],
	};
}

test("the stock endpoint requires an owner session", async t => {
	const db = await createDatabase();
	t.after(() => db.close());
	const server = await startServer(db, await makeCredentials());
	t.after(() => server.close());

	const response = await fetch(`${server.url}/api/owner/products/1/stock`, {
		method: "PATCH",
		headers: { Origin: OWNER_ORIGIN, "Content-Type": "application/json" },
		body: JSON.stringify({ delta: 1 }),
	});
	assert.equal(response.status, 401);
});

test("the stock endpoint applies a delta and a set, and never goes below zero", async t => {
	const db = await createDatabase();
	t.after(() => db.close());
	const server = await startServer(db, await makeCredentials());
	t.after(() => server.close());
	const session = await login(server);

	const plus = await ownerRequest(server, session, "PATCH", "/api/owner/products/1/stock", { delta: 5 });
	assert.equal(plus.status, 200);
	assert.equal(plus.rows, undefined);
	const plusBody = await plus.json();
	assert.equal(plusBody.product.stock, 8, "3 + 5 = 8");
	assert.equal(plusBody.product.low_stock_threshold, 5, "the list columns include the threshold");

	const floor = await ownerRequest(server, session, "PATCH", "/api/owner/products/1/stock", { delta: -100 });
	assert.equal(floor.status, 200);
	assert.equal((await floor.json()).product.stock, 0, "a negative delta floors at zero");

	const set = await ownerRequest(server, session, "PATCH", "/api/owner/products/1/stock", { set: 12 });
	assert.equal(set.status, 200);
	assert.equal((await set.json()).product.stock, 12);

	const soldOut = await ownerRequest(server, session, "PATCH", "/api/owner/products/2/stock", { delta: 1 });
	assert.equal((await soldOut.json()).product.stock, 1, "sold-out stock can be raised");
});

test("the stock endpoint rejects bad requests and unknown products", async t => {
	const db = await createDatabase();
	t.after(() => db.close());
	const server = await startServer(db, await makeCredentials());
	t.after(() => server.close());
	const session = await login(server);

	const both = await ownerRequest(server, session, "PATCH", "/api/owner/products/1/stock", { delta: 1, set: 2 });
	assert.equal(both.status, 400);

	const neither = await ownerRequest(server, session, "PATCH", "/api/owner/products/1/stock", {});
	assert.equal(neither.status, 400);

	const negativeSet = await ownerRequest(server, session, "PATCH", "/api/owner/products/1/stock", { set: -1 });
	assert.equal(negativeSet.status, 400);

	const fractional = await ownerRequest(server, session, "PATCH", "/api/owner/products/1/stock", { delta: 1.5 });
	assert.equal(fractional.status, 400);

	const unknown = await ownerRequest(server, session, "PATCH", "/api/owner/products/999/stock", { delta: 1 });
	assert.equal(unknown.status, 404);
});

test("checkout deducts stock, and the same idempotency key never deducts twice", async t => {
	const db = await createDatabase();
	t.after(() => db.close());
	const server = await startServer(db);
	t.after(() => server.close());

	const idempotencyKey = crypto.randomBytes(32).toString("base64url");
	const create = await fetch(`${server.url}/api/orders`, {
		method: "POST",
		headers: { "Content-Type": "application/json", "Idempotency-Key": idempotencyKey },
		body: JSON.stringify(checkoutBody()),
	});
	assert.equal(create.status, 201);
	assert.equal(await stockOf(db, 1), 1, "3 stock minus the ordered 2");

	const retry = await fetch(`${server.url}/api/orders`, {
		method: "POST",
		headers: { "Content-Type": "application/json", "Idempotency-Key": idempotencyKey },
		body: JSON.stringify(checkoutBody()),
	});
	assert.equal(retry.status, 200, "an idempotent retry returns the saved order");
	assert.equal(await stockOf(db, 1), 1, "the retry must not deduct a second time");
});

test("an order that would oversell is refused with the documented payload and nothing is written", async t => {
	const db = await createDatabase();
	t.after(() => db.close());
	const server = await startServer(db);
	t.after(() => server.close());

	// Product 1 has 3 in stock: five are too many.
	const order = checkoutBody();
	order.items = [{ product_id: 1, quantity: 5 }];
	const response = await fetch(`${server.url}/api/orders`, {
		method: "POST",
		headers: { "Content-Type": "application/json", "Idempotency-Key": crypto.randomBytes(32).toString("base64url") },
		body: JSON.stringify(order),
	});
	assert.equal(response.status, 409);
	const body = await response.json();
	assert.equal(body.error, "insufficient_stock");
	assert.equal(body.product_id, 1);
	assert.equal(body.product_name, "Pocari Sweat 330ml");
	assert.equal(body.available, 3);

	assert.equal(await stockOf(db, 1), 3, "no deduction is kept after the rollback");
	const orderCount = await db.query("SELECT count(*)::int AS n FROM orders");
	assert.equal(orderCount.rows[0].n, 0, "the refused order must not be saved");
});

test("cancelling an order returns its stock exactly once", async t => {
	const db = await createDatabase();
	t.after(() => db.close());
	const server = await startServer(db, await makeCredentials());
	t.after(() => server.close());
	const session = await login(server);

	// Seed the order by hand so the test states the starting stock explicitly.
	const items = await db.query(
		`INSERT INTO orders (customer_name, customer_contact, subtotal, total, status,
			pickup_type, pickup_date, pickup_time, requested_pickup_time)
		 VALUES ('Cancel Me', '0400000000', 10.50, 10.50, 'Pending', 'SCHEDULED', '2099-06-15', '13:30', '13:30')
		 RETURNING id`,
	);
	const orderId = items.rows[0].id;
	await db.query(
		`INSERT INTO order_items (order_id, product_id, quantity, price, product_name, unit_price, subtotal)
		 VALUES ($1, 1, 2, '2.50', 'Pocari Sweat 330ml', '2.50', '5.00')`,
		[orderId],
	);
	assert.equal(await stockOf(db, 1), 3);

	const cancel = await ownerRequest(server, session, "POST", `/api/owner/orders/${orderId}/status`, {
		status: "Cancelled",
		cancellation_reason: "Customer asked to cancel the order.",
	});
	assert.equal(cancel.status, 200);
	assert.equal(await stockOf(db, 1), 5, "the two units return to the shelf");

	// Cancelled is terminal: a repeat request with the same reason succeeds but
	// must not restock the shelf a second time.
	const repeat = await ownerRequest(server, session, "POST", `/api/owner/orders/${orderId}/status`, {
		status: "Cancelled",
		cancellation_reason: "Customer asked to cancel the order.",
	});
	assert.equal(repeat.status, 200);
	assert.equal(await stockOf(db, 1), 5, "a repeat cancel must not restore stock twice");
});

// The owner dashboard always sends a product's stored image back in the edit
// PATCH (the form keeps the current photo when no replacement is chosen).
// Legacy rows carry plain relative paths there, so such an edit must not be
// rejected: only a NEW or CHANGED image value has to pass URL validation.
test("editing a product keeps its stored plain legacy image path", async t => {
	const LEGACY = "images/products/pocari.jpg";
	const db = await createDatabase();
	t.after(() => db.close());
	const server = await startServer(db, await makeCredentials());
	t.after(() => server.close());
	const session = await login(server);

	await db.query("UPDATE products SET image = $1 WHERE id = 2", [LEGACY]);

	// The exact payload shape the dashboard sends when the owner changes only
	// the name and price: every other field, including the stored image, is
	// round-tripped unchanged.
	const edit = await ownerRequest(server, session, "PATCH", "/api/owner/products/2", {
		name: "Jufran Banana Sauce 560g",
		category: "Sauces",
		price: "5.50",
		stock: 0,
		original_price: null,
		image: LEGACY,
		description: "Banana sauce.",
	});
	assert.equal(edit.status, 200);
	const editBody = await edit.json();
	assert.equal(editBody.product.image, LEGACY, "the stored legacy path must survive the edit untouched");
	assert.equal(editBody.product.name, "Jufran Banana Sauce 560g");
	assert.equal(editBody.product.price, "5.50");
	const stored = await db.query("SELECT image FROM products WHERE id = 2");
	assert.equal(stored.rows[0].image, LEGACY, "the database row keeps its legacy image value");
});

test("changing a product to a different invalid relative image path is still refused", async t => {
	const LEGACY = "images/products/pocari.jpg";
	const db = await createDatabase();
	t.after(() => db.close());
	const server = await startServer(db, await makeCredentials());
	t.after(() => server.close());
	const session = await login(server);

	await db.query("UPDATE products SET image = $1 WHERE id = 2", [LEGACY]);

	// A NEW image value (one that differs from what the database stores) must
	// still pass the full URL validation.
	const rejected = await ownerRequest(server, session, "PATCH", "/api/owner/products/2", {
		name: "Jufran Banana Sauce 560g",
		price: "5.50",
		image: "images/products/jufran.jpg",
	});
	assert.equal(rejected.status, 400, "a changed relative path is not an uploaded photo");
	const rejectedBody = await rejected.json();
	assert.equal(rejectedBody.code, "INVALID_PRODUCT");
	const stored = await db.query("SELECT image FROM products WHERE id = 2");
	assert.equal(stored.rows[0].image, LEGACY, "the refused change must not have touched the stored image");
});

test("the stock endpoint is unaffected by a legacy image path", async t => {
	const LEGACY = "images/products/pocari.jpg";
	const db = await createDatabase();
	t.after(() => db.close());
	const server = await startServer(db, await makeCredentials());
	t.after(() => server.close());
	const session = await login(server);

	await db.query("UPDATE products SET image = $1 WHERE id = 2", [LEGACY]);

	const delta = await ownerRequest(server, session, "PATCH", "/api/owner/products/2/stock", { delta: 4 });
	assert.equal(delta.status, 200);
	const deltaBody = await delta.json();
	assert.equal(deltaBody.product.stock, 4, "0 + 4 = 4");
	assert.equal(deltaBody.product.image, LEGACY, "the stock response keeps the stored image");

	const set = await ownerRequest(server, session, "PATCH", "/api/owner/products/2/stock", { set: 2 });
	assert.equal(set.status, 200);
	assert.equal((await set.json()).product.stock, 2);
	assert.equal(await stockOf(db, 2), 2);
});

