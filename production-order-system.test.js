	const db = await createLegacyDatabase();
	t.after(() => db.close());
	await applyMigration(db);

	// Product 999 does not exist, so the pricing lookup fails before the order
	// row is even inserted. The order count must not change.
	const before = await db.query("SELECT count(*)::int AS n FROM orders");

