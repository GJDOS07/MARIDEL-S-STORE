test("checkout, idempotent retry, tracking and order retrieval work on the migrated schema", async t => {
	const db = await createLegacyDatabase();
	t.after(() => db.close());
	await applyMigration(db);
	const pool = createRealPool(db);
	const server = await startRealServer(pool, { secureCookies: false });
	t.after(() => server.close());

	// Order 8 is the first the app creates on this migrated database.
	const idempotencyKey = createIdempotencyKey();
	const create = await fetch(`${server.url}/api/orders`, {
		method: "POST",
		headers: { "Content-Type": "application/json", "Idempotency-Key": idempotencyKey },
		body: JSON.stringify(ORDER),
	});
	assert.equal(create.status, 201, "checkout must succeed against the migrated schema");
	const saved = await create.json();
	assert.equal(saved.order_number, "MS-8");
	assert.equal(saved.total, "5.00");
	assert.match(saved.tracking_token, /^[A-Za-z0-9_-]{43}$/);

	// The API derives order_number as 'MS-' || id in JavaScript, so a correct
	// response does NOT prove the column was written. Assert it directly: the
	// earlier NOT NULL defect was exactly a statement that looked right here.
	const numberRow = await db.query("SELECT order_number FROM orders WHERE id = 8");
	assert.equal(numberRow.rows[0].order_number, "MS-8", "order_number must be persisted in the row");

	// Order items were really persisted.
	const items = await db.query("SELECT product_id, quantity, unit_price, subtotal FROM order_items WHERE order_id = 8");
	assert.equal(items.rows.length, 1);
	assert.equal(items.rows[0].product_id, 1);
	assert.equal(items.rows[0].quantity, 2);
	assert.equal(items.rows[0].subtotal, "5.00");

	// The stored credential hash matches the returned credential, and no
	// plaintext was written to the legacy column.
	const stored = await db.query("SELECT tracking_token_hash, customer_access_token FROM orders WHERE id = 8");
	assert.equal(stored.rows[0].tracking_token_hash,
		crypto.createHash("sha256").update(saved.tracking_token).digest("hex"));
	assert.equal(stored.rows[0].customer_access_token, null);

	// Idempotent retry with the same key and the same payload returns the same
	// order without creating a duplicate.
	const retry = await fetch(`${server.url}/api/orders`, {
		method: "POST",
		headers: { "Content-Type": "application/json", "Idempotency-Key": idempotencyKey },
		body: JSON.stringify(ORDER),
	});
	assert.equal(retry.status, 200);
	assert.equal((await retry.json()).order_number, "MS-8");
	const orderCount = await db.query("SELECT count(*)::int AS n FROM orders");
	assert.equal(orderCount.rows[0].n, 8, "an idempotent retry must not create a second order");

	// A changed payload with the same key conflicts.
	const conflict = await fetch(`${server.url}/api/orders`, {
		method: "POST",
		headers: { "Content-Type": "application/json", "Idempotency-Key": idempotencyKey },
		body: JSON.stringify({ ...ORDER, customer_contact: "0411111111" }),
	});
	assert.equal(conflict.status, 409);

	// Tracking works with the returned credential.
	const tracked = await fetch(`${server.url}/api/orders/track`, {
		method: "POST",
		headers: { "Content-Type": "application/json" },
		body: JSON.stringify({ token: saved.tracking_token }),
	});
	assert.equal(tracked.status, 200, "the migrated tracking column must be usable");
	const trackedBody = await tracked.json();
	assert.equal(trackedBody.order_number, "MS-8");

	// Order retrieval by numeric id plus bearer works, and a bare numeric id fails.
	const byId = await fetch(`${server.url}/api/orders/8`, {
		headers: { Authorization: `Bearer ${saved.tracking_token}` },
	});
	assert.equal(byId.status, 200);
	const bare = await fetch(`${server.url}/api/orders/8`);
	assert.equal(bare.status, 404, "a numeric id without a credential must not expose an order");
});

