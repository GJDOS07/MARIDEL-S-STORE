test("backfills order_number as MS-<id> and enforces uniqueness", async t => {
	const db = await createLegacyDatabase();
	t.after(() => db.close());

	await applyMigration(db);

	const rows = await db.query("SELECT id, order_number FROM orders ORDER BY id");
	assert.equal(rows.rows.length, 7);
	for (const row of rows.rows) {
		assert.equal(row.order_number, `MS-${row.id}`, `order ${row.id} must be backfilled as MS-${row.id}`);
	}

	// The unique index rejects a duplicate order_number.
	await assert.rejects(
		db.query("UPDATE orders SET order_number = 'MS-1' WHERE id = 2"),
		/unique|duplicate/i,
		"a duplicate order_number must be rejected",
	);

	// order_number is nullable by design: an order is inserted before its id is
	// known, so the application writes the number in a follow-up UPDATE inside
	// the same transaction. What matters is that the UNIQUE index still rejects a
	// duplicate, which is verified above.
	await assert.rejects(
		db.query("UPDATE orders SET order_number = 'MS-1' WHERE id = 2"),
		/unique|duplicate/i,
		"a duplicate order_number must be rejected",
	);
	await clearAbortedTransaction(db);
});

test("accepts all seven allowed statuses and corrects the cold default", async t => {
	const db = await createLegacyDatabase();
	t.after(() => db.close());

	await applyMigration(db);

	// Every seeded status survived, proving the constraint preserved them.
	const rows = await db.query("SELECT DISTINCT status FROM orders ORDER BY status");
	assert.deepEqual(rows.rows.map(r => r.status).sort(), [...ALL_STATUSES].sort());

	// Every status the application writes is accepted by the constraint.
	for (const status of ALL_STATUSES) {
		await db.query("INSERT INTO orders (subtotal, total, status, order_number) VALUES (0, 0, $1, $2)",
			[status, `MS-${status.replace(/\W+/g, "")}`]);
	}

	// The cold default is 'Pending', not lowercase 'pending'.
	const defaultRow = await db.query(
		"SELECT column_default FROM information_schema.columns WHERE table_schema='public' AND table_name='orders' AND column_name='status'",
	);
	assert.match(String(defaultRow.rows[0].column_default), /Pending/);

	// An unknown status is rejected.
	await assert.rejects(
		db.query("INSERT INTO orders (subtotal, total, status, order_number) VALUES (0, 0, 'Awaiting Payment', 'MS-BAD')"),
		/check constraint|violates/i,
		"an unknown status must be rejected",
	);
	await clearAbortedTransaction(db);
});

test("enforces the hash-format constraints on new tracking and fingerprint values", async t => {
	const db = await createLegacyDatabase();
	t.after(() => db.close());
	await applyMigration(db);

	const validHash = crypto.createHash("sha256").update("x").digest("hex");
	assert.equal(validHash.length, 64);

	// Well-formed 64-char lowercase hex is accepted.
	await db.query("UPDATE orders SET tracking_token_hash = $1, idempotency_fingerprint = $1 WHERE id = 1", [validHash]);
	const row = await db.query("SELECT tracking_token_hash, idempotency_fingerprint FROM orders WHERE id = 1");
	assert.equal(row.rows[0].tracking_token_hash, validHash);
	assert.equal(row.rows[0].idempotency_fingerprint, validHash);

	// NULL remains allowed, which is what legacy rows need.
	await db.query("UPDATE orders SET tracking_token_hash = NULL, idempotency_fingerprint = NULL WHERE id = 1");
	const nulled = await db.query("SELECT tracking_token_hash FROM orders WHERE id = 1");
	assert.equal(nulled.rows[0].tracking_token_hash, null);

	// A malformed hash is rejected by the CHECK constraints.
	for (const bad of ["not-a-hash", "A".repeat(64), "a".repeat(63), "z".repeat(64)]) {
		await assert.rejects(
			db.query("UPDATE orders SET tracking_token_hash = $1 WHERE id = 1", [bad]),
			/check constraint|violates/i,
			`tracking_token_hash "${bad.slice(0, 12)}..." must be rejected`,
		);
		await clearAbortedTransaction(db);
	}
});

test("enforces the 3-500 character cancellation reason rule", async t => {
	const db = await createLegacyDatabase();
	t.after(() => db.close());
	await applyMigration(db);

	// NULL is allowed: only cancelled orders carry a reason.
	await db.query("UPDATE orders SET cancellation_reason = NULL WHERE id = 1");

	// A whitespace-only reason is NOT allowed: btrim() reduces it to zero
	// characters, which is outside the 3-500 rule the order status API enforces.
	await assert.rejects(
		db.query("UPDATE orders SET cancellation_reason = '   ' WHERE id = 1"),
		/orders_cancellation_reason_check|check constraint/i,
		"a whitespace-only cancellation_reason must be rejected",
	);
	await clearAbortedTransaction(db);

	// Valid reasons are accepted.
	await db.query("UPDATE orders SET cancellation_reason = 'Customer requested cancellation' WHERE id = 1");
	const row = await db.query("SELECT cancellation_reason FROM orders WHERE id = 1");
	assert.equal(row.rows[0].cancellation_reason, "Customer requested cancellation");

	// Too short (fewer than 3 non-space characters) and too long are rejected.
	for (const bad of ["ab", "a".repeat(501)]) {
		await assert.rejects(
			db.query("UPDATE orders SET cancellation_reason = $1 WHERE id = 1", [bad]),
			/check constraint|violates/i,
			"cancellation_reason outside 3-500 characters must be rejected",
		);
		await clearAbortedTransaction(db);
	}
});

