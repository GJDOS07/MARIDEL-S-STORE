async function makeOwnerCredentials() {
	const salt = crypto.randomBytes(16);
	const digest = await scrypt(OWNER_PASSWORD, salt, 64);
	return {
		ownerPasswordHash: `scrypt$${salt.toString("hex")}$${digest.toString("hex")}`,
		sessionSecret: crypto.randomBytes(32).toString("base64url"),
	};
}

async function ownerLogin(server, ownerPasswordHash, sessionSecret) {
	const csrfResponse = await fetch(`${server.url}/api/owner/csrf`, { headers: { Origin: OWNER_ORIGIN } });
	assert.equal(csrfResponse.status, 200);
	const csrfBody = await csrfResponse.json();
	const cookieJar = csrfResponse.headers.getSetCookie().map(cookie => cookie.split(";")[0]);

	const loginResponse = await fetch(`${server.url}/api/owner/login`, {
		method: "POST",
		headers: {
			"Content-Type": "application/json",
			Origin: OWNER_ORIGIN,
			Cookie: cookieJar.join("; "),
			"X-CSRF-Token": csrfBody.csrf_token,
		},
		body: JSON.stringify({ password: OWNER_PASSWORD }),
	});
	assert.equal(loginResponse.status, 200, "owner login must succeed against the migrated schema");
	const loginBody = await loginResponse.json();
	assert.equal(loginBody.authenticated, true);

	const loginCookies = [...cookieJar, ...loginResponse.headers.getSetCookie().map(cookie => cookie.split(";")[0])];
	return { cookies: loginCookies.join("; "), csrfToken: loginBody.csrf_token };
}

