test("owner order listing, status transitions and cancellation persist a reason", async t => {
	const db = await createLegacyDatabase();
	t.after(() => db.close());
	await applyMigration(db);
	const pool = createRealPool(db);
	const { ownerPasswordHash, sessionSecret } = await makeOwnerCredentials();
	const server = await startRealServer(pool, { ownerPasswordHash, sessionSecret, secureCookies: false });
	t.after(() => server.close());

	const unauthenticated = await fetch(`${server.url}/api/owner/orders`, { headers: { Origin: OWNER_ORIGIN } });
	assert.equal(unauthenticated.status, 401, "owner order list must stay protected");

	const { cookies, csrfToken } = await ownerLogin(server, ownerPasswordHash, sessionSecret);

	const list = await fetch(`${server.url}/api/owner/orders`, { headers: { Origin: OWNER_ORIGIN, Cookie: cookies } });
	assert.equal(list.status, 200, "owner order list must read cancellation_reason from the migrated schema");
	const listBody = await list.json();
	assert.ok(Array.isArray(listBody));
	// Order 1 holds the 'Pending' status, from which 'Confirmed' is a valid
	// forward transition.
	assert.ok(listBody.some(order => order.order_number === "MS-1"));

	const detail = await fetch(`${server.url}/api/owner/orders/1`, { headers: { Origin: OWNER_ORIGIN, Cookie: cookies } });
	assert.equal(detail.status, 200);
	assert.equal((await detail.json()).order_number, "MS-1");

	// A forward transition succeeds.
	const confirmed = await fetch(`${server.url}/api/owner/orders/1/status`, {
		method: "POST",
		headers: { "Content-Type": "application/json", Origin: OWNER_ORIGIN, Cookie: cookies, "X-CSRF-Token": csrfToken },
		body: JSON.stringify({ status: "Confirmed" }),
	});
	assert.equal(confirmed.status, 200);
	assert.equal((await confirmed.json()).status, "Confirmed");

	// Once confirmed, 'Pending' is not a permitted transition back.
	const illegal = await fetch(`${server.url}/api/owner/orders/1/status`, {
		method: "POST",
		headers: { "Content-Type": "application/json", Origin: OWNER_ORIGIN, Cookie: cookies, "X-CSRF-Token": csrfToken },
		body: JSON.stringify({ status: "Pending" }),
	});
	assert.equal(illegal.status, 409);

	// Cancellation with a persisted reason.
	const reason = "Customer changed their mind at pickup";
	const cancelled = await fetch(`${server.url}/api/owner/orders/1/status`, {
		method: "POST",
		headers: { "Content-Type": "application/json", Origin: OWNER_ORIGIN, Cookie: cookies, "X-CSRF-Token": csrfToken },
		body: JSON.stringify({ status: "Cancelled", cancellation_reason: reason }),
	});
	assert.equal(cancelled.status, 200);
	assert.equal((await cancelled.json()).cancellation_reason, reason);

	const stored = await db.query("SELECT status, cancellation_reason FROM orders WHERE id = 1");
	assert.equal(stored.rows[0].status, "Cancelled");
	assert.equal(stored.rows[0].cancellation_reason, reason, "the reason must be persisted in the new column");

	// The reason is immutable once cancelled.
	const reCancel = await fetch(`${server.url}/api/owner/orders/1/status`, {
		method: "POST",
		headers: { "Content-Type": "application/json", Origin: OWNER_ORIGIN, Cookie: cookies, "X-CSRF-Token": csrfToken },
		body: JSON.stringify({ status: "Cancelled", cancellation_reason: "Different reason entirely" }),
	});
	assert.equal(reCancel.status, 409, "a cancellation reason must be immutable after cancellation");

	// A too-short reason is rejected before it reaches the database.
	const badReason = await fetch(`${server.url}/api/owner/orders/4/status`, {
		method: "POST",
		headers: { "Content-Type": "application/json", Origin: OWNER_ORIGIN, Cookie: cookies, "X-CSRF-Token": csrfToken },
		body: JSON.stringify({ status: "Cancelled", cancellation_reason: "no" }),
	});
	assert.equal(badReason.status, 400);
});
