// Synthetic historical data. Credentials below are random test fixtures, never
// production values, and are only compared to verify the migration leaves them
// untouched. They are deliberately 40+ characters because POST /api/orders/track
// rejects any credential shorter than 40 or longer than 512 characters before
// it queries the database; every verified legacy production credential is
// already inside that range.
const LEGACY_TOKEN_SUFFIX = "0000000000000000000000000000000001";

async function seedLegacyData(db) {
	await db.query("INSERT INTO products (id, name, category, price, image, description) VALUES ($1, $2, $3, $4, $5, $6)",
		[1, "Pocari Sweat 330ml", "Drinks", "2.50", null, "Ion supply drink."]);
	await db.query("INSERT INTO products (id, name, category, price, image, description) VALUES ($1, $2, $3, $4, $5, $6)",
		[2, "Jufran Banana Sauce 560g", "Sauces", "2.00", null, "Banana sauce."]);

	await db.query("INSERT INTO customers (id, gmail) VALUES ($1, $2)", [1, "customer-one@example.test"]);
	await db.query("INSERT INTO customers (id, gmail) VALUES ($1, $2)", [2, "customer-two@example.test"]);

	// Seven orders, one per allowed status, each with a legacy credential.
	// The legacy idempotency keys must be distinct because production has a
	// unique index on orders.idempotency_key.
	const statuses = ALL_STATUSES;
	for (let index = 0; index < statuses.length; index += 1) {
		const orderId = index + 1;
		const total = "5.00";
		const status = statuses[index];
		const customerName = `Legacy Customer ${orderId}`;
		const customerContact = "0400000000";
		const pickupDate = "2026-03-10";
		const pickupTime = "13:30";
		// Legacy plaintext credentials. Production has a unique index on this
		// column, so each order needs a distinct value, and the tracking
		// endpoint rejects anything shorter than 40 characters.
		const credential = `legacy-credential-${String(index + 1).padStart(2, "0")}-${LEGACY_TOKEN_SUFFIX}`;
		const idempotencyKey = String(index + 1).repeat(64);

		await db.query(
			`INSERT INTO orders (id, customer_id, subtotal, discount, shipping_fee, total, status,
				customer_name, customer_contact, pickup_type, pickup_date, pickup_time,
				requested_pickup_time, total_amount, customer_access_token, idempotency_key)
			 VALUES ($1, $2, $3, 0, 0, $4, $5, $6, $7, 'SCHEDULED', $8, $9, $9, $4, $10, $11)`,
			[
				orderId,
				(orderId % 2) + 1,
				total,
				total,
				status,
				customerName,
				customerContact,
				pickupDate,
				pickupTime,
				credential,
				idempotencyKey,
			],
		);
		await db.query(
			`INSERT INTO order_items (order_id, product_id, quantity, price, product_name, unit_price, subtotal)
			 VALUES ($1, $2, $3, $4, $5, $6, $7)`,
			[orderId, (orderId % 2) + 1, 2, "2.50", "Pocari Sweat 330ml", "2.50", "5.00"],
		);
	}

	// The fixture inserts explicit ids, and GENERATED BY DEFAULT AS IDENTITY (like
	// a plain DEFAULT nextval sequence in production) does not advance the
	// sequence on its own. Without this, the first application INSERT would
	// collide with an existing primary key.
	for (const table of ["orders", "order_items", "products", "customers"]) {
		await db.query(
			"SELECT setval(pg_get_serial_sequence($1, 'id'), GREATEST((SELECT COALESCE(MAX(id), 0) FROM public." + table + "), 1), true)",
			["public." + table],
		);
	}
}

async function createLegacyDatabase() {
	const db = await PGlite.create();
	await db.exec(LEGACY_SCHEMA);
	await seedLegacyData(db);
	return db;
}

// A failed migration aborts the transaction; clear it so the instance stays
// queryable for the "nothing was applied" assertions.
async function clearAbortedTransaction(db) {
	try {
		await db.exec("ROLLBACK;");
	} catch {
		// No transaction was open; nothing to clear.
	}
}

async function objectPresence(db) {
	const result = {};
	for (const [object, kind] of REQUIRED_OBJECTS) {
		const column = kind === "column" ? object.replace("orders.", "") : null;
		const row = kind === "column"
			? await db.query(
				"SELECT count(*)::int AS n FROM information_schema.columns WHERE table_schema='public' AND table_name='orders' AND column_name=$1",
				[column],
			)
			: await db.query(
				"SELECT count(*)::int AS n FROM information_schema.tables WHERE table_schema='public' AND table_name=$1",
				[object.replace("public.", "")],
			);
		result[object] = row.rows[0].n === 1;
	}
	for (const name of REQUIRED_CONSTRAINTS) {
		const row = await db.query(
			"SELECT count(*)::int AS n FROM pg_constraint WHERE connamespace='public'::regnamespace AND conname=$1",
			[name],
		);
		result[name] = row.rows[0].n === 1;
	}
	for (const name of REQUIRED_INDEXES) {
		const row = await db.query(
			"SELECT count(*)::int AS n FROM pg_indexes WHERE schemaname='public' AND indexname=$1",
			[name],
		);
		result[name] = row.rows[0].n === 1;
	}
	return result;
}

async function applyMigration(db) {
	await db.exec(MIGRATION_SQL);
}

