const MELBOURNE_DATE_FORMAT = new Intl.DateTimeFormat("en-CA", {
	timeZone: "Australia/Melbourne",
	year: "numeric",
	month: "2-digit",
	day: "2-digit",
});

function melbourneDate(instant) {
	return MELBOURNE_DATE_FORMAT.format(instant);
}

// Calendar-day arithmetic on a date-only value, done in UTC so the server's
// own time zone is never involved.
function addDays(date, days) {
	const [year, month, day] = date.split("-").map(Number);
	return new Date(Date.UTC(year, month - 1, day + days)).toISOString().slice(0, 10);
}

// --- month helpers for the monthly history test ------------------------------
// Same UTC-first rule as addDays, but on YYYY-MM month keys.
function previousMonthOf(monthKey) {
	const [year, month] = monthKey.split("-").map(Number);
	return month === 1
		? `${year - 1}-12`
		: `${year}-${String(month - 1).padStart(2, "0")}`;
}

// Days in a YYYY-MM month: day 0 of the following month is its last day.
function daysInMonth(monthKey) {
	const [year, month] = monthKey.split("-").map(Number);
	return new Date(Date.UTC(year, month, 0)).getUTCDate();
}

// Every YYYY-MM key from start to end inclusive, oldest first.
function enumerateMonths(startKey, endKey) {
	const [startYear, startMonth] = startKey.split("-").map(Number);
	const months = [];
	for (let year = startYear, month = startMonth; ;) {
		months.push(`${year}-${String(month).padStart(2, "0")}`);
		const current = `${year}-${String(month).padStart(2, "0")}`;
		if (current >= endKey) break;
		month += 1;
		if (month > 12) {
			month = 1;
			year += 1;
		}
	}
	return months;
}

function money(amount) {
	return amount.toFixed(2);
}

function melbourneDateOfUtcTimestamp(timestamp) {
	// timestamp is "YYYY-MM-DD HH:MM:SS" and is UTC, exactly how the column
	// stores it. The trailing Z makes the instant unambiguous.
	return melbourneDate(new Date(`${timestamp.replace(" ", "T")}Z`));
}

