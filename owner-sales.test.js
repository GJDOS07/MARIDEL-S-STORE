// Integration tests for GET /api/owner/sales, run against a REAL isolated
// PostgreSQL (PGlite/WASM, in-memory). Every period is bucketed by the order
// date in Australia/Melbourne, so the fixtures deliberately include an order
// whose UTC date and Melbourne date differ.
//
// Production is never contacted: the test creates its own in-memory database.

const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const { promisify } = require("node:util");
const express = require("express");

const { PGlite } = require("@electric-sql/pglite");
const { createOrderRouter } = require("./order-routes");
const { createApiErrorHandler } = require("./api-error-handler");

const scrypt = promisify(crypto.scrypt);
const root = __dirname;
const MIGRATION = fs.readFileSync(path.join(root, "owner-account-and-products.sql"), "utf8");
const ORDER_MIGRATION = fs.readFileSync(path.join(root, "production-order-system.sql"), "utf8");

const OWNER_ORIGIN = "https://store.example";
const OWNER_PASSWORD = "synthetic-owner-password-123";

// The same legacy schema the owner endpoint integration tests use, mirroring
// the products/orders/order_items tables before either migration runs.
// orders.created_at is TIMESTAMP WITHOUT TIME ZONE, which stores UTC.
const LEGACY_SCHEMA = `
CREATE TABLE products (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR NOT NULL,
	category VARCHAR,
	price NUMERIC NOT NULL,
	original_price NUMERIC,
	image TEXT,
	description TEXT,
	stock INTEGER DEFAULT 0,
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE orders (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	customer_id INTEGER,
	subtotal NUMERIC NOT NULL,
	discount NUMERIC DEFAULT 0,
	shipping_fee NUMERIC DEFAULT 0,
	total NUMERIC NOT NULL,
	status VARCHAR DEFAULT 'Pending',
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	customer_name TEXT,
	customer_contact TEXT,
	customer_email TEXT,
	pickup_type TEXT,
	pickup_date DATE,
	pickup_time TEXT,
	requested_pickup_time TEXT,
	total_amount NUMERIC,
	customer_access_token TEXT,
	idempotency_key TEXT,
	order_number TEXT,
	tracking_token_hash CHAR(64),
	idempotency_fingerprint CHAR(64),
	cancellation_reason TEXT
);

CREATE TABLE order_items (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	order_id INTEGER REFERENCES orders(id) ON DELETE CASCADE,
	product_id INTEGER,
	quantity INTEGER NOT NULL,
	price NUMERIC NOT NULL,
	product_name TEXT,
	unit_price NUMERIC,
	subtotal NUMERIC
);

CREATE TABLE owner_sessions (
	session_hash CHAR(64) PRIMARY KEY CHECK (session_hash ~ '^[a-f0-9]{64}$'),
	expires_at TIMESTAMPTZ NOT NULL,
	created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS owner_sessions_expires_at_idx ON public.owner_sessions (expires_at);

CREATE TABLE owner_login_attempts (
	client_key_hash CHAR(64) PRIMARY KEY CHECK (client_key_hash ~ '^[a-f0-9]{64}$'),
	window_started_at TIMESTAMPTZ NOT NULL,
	attempt_count INTEGER NOT NULL CHECK (attempt_count BETWEEN 1 AND 1000000)
);
`;

const MELBOURNE_DATE_FORMAT = new Intl.DateTimeFormat("en-CA", {
	timeZone: "Australia/Melbourne",
	year: "numeric",
	month: "2-digit",
	day: "2-digit",
});

function melbourneDate(instant) {
	return MELBOURNE_DATE_FORMAT.format(instant);
}

// Calendar-day arithmetic on a date-only value, done in UTC so the server's
// own time zone is never involved.
function addDays(date, days) {
	const [year, month, day] = date.split("-").map(Number);
	return new Date(Date.UTC(year, month - 1, day + days)).toISOString().slice(0, 10);
}

function money(amount) {
	return amount.toFixed(2);
}

function melbourneDateOfUtcTimestamp(timestamp) {
	// timestamp is "YYYY-MM-DD HH:MM:SS" and is UTC, exactly how the column
	// stores it. The trailing Z makes the instant unambiguous.
	return melbourneDate(new Date(`${timestamp.replace(" ", "T")}Z`));
}

async function createDatabase() {
	const db = await PGlite.create();
	await db.exec(LEGACY_SCHEMA);

	// The shared owner fixture's catalog. Ids 73 and 74 are the historical
	// products the other owner tests use; the rest are filler.
	for (let index = 1; index <= 18; index += 1) {
		const id = index === 1 ? 73 : index === 2 ? 74 : index;
		const name = id === 73
			? "Pocari Sweat 330ml"
			: id === 74 ? "Jufran Banana Sauce 560g" : `Legacy Product ${id}`;
		await db.query(
			"INSERT INTO products (id, name, category, price, description, stock) VALUES ($1,$2,$3,$4,$5,$6)",
			[
				id,
				name,
				id % 2 === 0 ? "Sauces" : "Drinks",
				id === 73 ? "55.00" : id === 74 ? "2.50" : `${id}.50`,
				id === 73 ? "Ion supply drink." : id === 74 ? "Banana sauce." : `Description ${id}.`,
				id,
			],
		);
	}

	await db.query(
		`INSERT INTO orders (id, customer_id, subtotal, total, status, customer_name, customer_contact,
			pickup_type, pickup_date, pickup_time, requested_pickup_time, total_amount, customer_access_token, idempotency_key, order_number)
		 VALUES (1, NULL, 110.00, 110.00, 'Pending', 'Legacy Customer', '0400000000',
			'SCHEDULED', '2026-03-10', '13:30', '13:30', 110.00,
			'legacy-credential-0000000000000000000000000000000001', $1, 'MS-1')`,
		["9".repeat(64)],
	);
	await db.query(
		"INSERT INTO order_items (order_id, product_id, quantity, price, product_name, unit_price, subtotal) VALUES ($1,$2,$3,$4,$5,$6,$7)",
		[1, 73, 2, "55.00", "Pocari Sweat 330ml", "55.00", "110.00"],
	);

	await db.exec(ORDER_MIGRATION);
	await db.exec(MIGRATION);

	// The fixture inserts explicit ids, and GENERATED BY DEFAULT AS IDENTITY does
	// not advance the sequences on its own, so a later create would collide.
	for (const table of ["products", "orders", "order_items"]) {
		await db.query(
			"SELECT setval(pg_get_serial_sequence($1, 'id'), GREATEST((SELECT COALESCE(MAX(id), 0) FROM public." + table + "), 1), true)",
			["public." + table],
		);
	}

	// Every test logs in from 127.0.0.1, so each test needs a clean rate-limit
	// budget exactly as a separate deployment would have.
	await db.query("DELETE FROM owner_login_attempts");

	return db;
}

function createRealPool(db) {
	// PGlite returns rows: [] for statements without RETURNING and reports the
	// affected count separately, so rowCount must come from affectedRows when
	// present. A DELETE that matched rows otherwise looks like a 404.
	const shape = (result) => ({
		rows: result.rows,
		rowCount: typeof result.affectedRows === "number" && result.rows.length === 0
			? result.affectedRows
			: result.rows.length,
		fields: result.fields,
	});
	return {
		async query(sql, params = []) {
			const result = await db.query(sql, params);
			return shape(result);
		},
		async connect() {
			return {
				async query(sql, params = []) {
					const result = await db.query(sql, params);
					return shape(result);
				},
				release() {},
			};
		},
	};
}

async function startServer(db, options = {}) {
	const app = express();
	app.use(express.json({ limit: "1mb" }));
	app.use("/api", createOrderRouter(createRealPool(db), {
		allowedOrigins: [OWNER_ORIGIN],
		secureCookies: false,
		...options,
	}));
	app.use(createApiErrorHandler({ error() {} }));
	const server = app.listen(0, "127.0.0.1");
	await new Promise(resolve => server.once("listening", resolve));
	return {
		url: `http://127.0.0.1:${server.address().port}`,
		close: () => new Promise((resolve, reject) => server.close(error => (error ? reject(error) : resolve()))),
	};
}

async function makeCredentials() {
	const salt = crypto.randomBytes(16);
	const digest = await scrypt(OWNER_PASSWORD, salt, 64);
	return {
		ownerPasswordHash: `scrypt$${salt.toString("hex")}$${digest.toString("hex")}`,
		sessionSecret: crypto.randomBytes(32).toString("base64url"),
	};
}

async function attemptLogin(server, password) {
	const csrf = await fetch(`${server.url}/api/owner/csrf`, { headers: { Origin: OWNER_ORIGIN } });
	const csrfBody = await csrf.json();
	const jar = csrf.headers.getSetCookie().map(cookie => cookie.split(";")[0]);
	return fetch(`${server.url}/api/owner/login`, {
		method: "POST",
		headers: {
			Origin: OWNER_ORIGIN,
			"Content-Type": "application/json",
			Cookie: jar.join("; "),
			"X-CSRF-Token": csrfBody.csrf_token,
		},
		body: JSON.stringify({ password }),
	});
}

async function login(server, password = OWNER_PASSWORD) {
	const response = await attemptLogin(server, password);
	assert.equal(response.status, 200, "login must succeed");
	const body = await response.json();
	const cookieJar = response.headers.getSetCookie().map(cookie => cookie.split(";")[0]);
	return { cookies: cookieJar.join("; "), csrfToken: body.csrf_token };
}

function ownerRequest(server, session, method, url, body) {
	return fetch(`${server.url}${url}`, {
		method,
		headers: {
			Origin: OWNER_ORIGIN,
			"Content-Type": "application/json",
			Cookie: session.cookies,
			"X-CSRF-Token": session.csrfToken,
		},
		body: body === undefined ? undefined : JSON.stringify(body),
	});
}

async function insertSalesOrder(db, order) {
	const result = await db.query(
		`INSERT INTO orders (
			customer_name, customer_contact, customer_email, subtotal, discount,
			shipping_fee, total, status, pickup_type, pickup_date, pickup_time,
			requested_pickup_time, created_at
		) VALUES ($1,$2,$3,$4,$5,$6,$7,$8,'SCHEDULED','2099-06-15','13:30','13:30',$9)
		RETURNING id`,
		[
			order.customerName,
			"0400000000",
			order.email,
			order.subtotal,
			order.discount,
			order.shippingFee,
			order.total.toFixed(2),
			order.status,
			order.createdAt,
		],
	);
	return Number(result.rows[0].id);
}

test("owner sales summary buckets orders by Melbourne order date", async t => {
	const db = await createDatabase();
	t.after(() => db.close());

	// The shared fixture seeds an order with the current time. Remove it so the
	// expected totals below come only from this test's explicit fixtures.
	await db.query("DELETE FROM orders");

	const server = await startServer(db, await makeCredentials());
	t.after(() => server.close());

	// 401 without an owner session, exactly like the other owner routes.
	const unauthorized = await fetch(`${server.url}/api/owner/sales`, { headers: { Origin: OWNER_ORIGIN } });
	assert.equal(unauthorized.status, 401);
	assert.equal((await unauthorized.json()).code, "OWNER_LOGIN_REQUIRED");

	const session = await login(server);

	const today = melbourneDate(new Date());
	const isoWeekday = new Date(`${today}T00:00:00.000Z`).getUTCDay() || 7;
	const weekStart = addDays(today, -(isoWeekday - 1));
	const monthStart = `${today.slice(0, 8)}01`;
	const dailyStart = addDays(today, -13);
	const yesterday = addDays(today, -1);
	const [currentYear, currentMonth] = today.split("-").map(Number);
	const previousMonthDate = new Date(Date.UTC(currentYear, currentMonth - 2, 15)).toISOString().slice(0, 10);

	// Each fixture is written with an explicit UTC timestamp. The "midnight"
	// order is at 14:30 UTC on the previous UTC day, which is 00:30 or 01:30
	// on the current Melbourne day, so its UTC date and Melbourne date differ.
	const fixtures = [
		{
			key: "today",
			customerName: "Today Customer",
			email: "today@example.com",
			createdAt: `${today} 02:00:00`,
			total: 12,
			subtotal: "13.00",
			discount: "2.00",
			shippingFee: "1.00",
			status: "Confirmed",
		},
		{
			key: "midnight",
			customerName: "Midnight Customer",
			email: "midnight@example.com",
			createdAt: `${yesterday} 14:30:00`,
			total: 25,
			subtotal: "25.00",
			discount: "0.00",
			shippingFee: "0.00",
			status: "Picked Up",
		},
		{
			key: "week",
			customerName: "This Week Customer",
			email: "week@example.com",
			createdAt: `${weekStart} 02:00:00`,
			total: 20,
			subtotal: "20.00",
			discount: "0.00",
			shippingFee: "0.00",
			status: "Confirmed",
		},
		{
			key: "month",
			customerName: "This Month Customer",
			email: "month@example.com",
			createdAt: `${monthStart} 02:00:00`,
			total: 40,
			subtotal: "40.00",
			discount: "0.00",
			shippingFee: "0.00",
			status: "Confirmed",
		},
		{
			key: "older",
			customerName: "Older Customer",
			email: "older@example.com",
			createdAt: `${previousMonthDate} 02:00:00`,
			total: 80,
			subtotal: "80.00",
			discount: "0.00",
			shippingFee: "0.00",
			status: "Confirmed",
		},
		{
			key: "cancelled",
			customerName: "Cancelled Customer",
			email: "cancelled@example.com",
			createdAt: `${today} 04:00:00`,
			total: 999,
			subtotal: "999.00",
			discount: "0.00",
			shippingFee: "0.00",
			status: "Cancelled",
		},
	];

	const ids = {};
	for (const fixture of fixtures) {
		ids[fixture.key] = await insertSalesOrder(db, fixture);
		fixture.melbourneDate = melbourneDateOfUtcTimestamp(fixture.createdAt);
	}

	// The point of the midnight fixture: the stored UTC day is not the day the
	// owner dashboard must count it on.
	assert.equal(fixtures.find(fixture => fixture.key === "midnight").melbourneDate, today);
	assert.notEqual(
		fixtures.find(fixture => fixture.key === "midnight").createdAt.slice(0, 10),
		today,
		"the midnight fixture must have a different UTC date",
	);

	const expectedPeriod = (startDate) => {
		const included = fixtures.filter(fixture => fixture.status !== "Cancelled"
			&& fixture.melbourneDate <= today
			&& (startDate === null || fixture.melbourneDate >= startDate));
		return {
			sales: money(included.reduce((sum, fixture) => sum + fixture.total, 0)),
			orders: included.length,
			collected: money(included
				.filter(fixture => fixture.status === "Picked Up")
				.reduce((sum, fixture) => sum + fixture.total, 0)),
		};
	};

	const response = await ownerRequest(server, session, "GET", "/api/owner/sales");
	assert.equal(response.status, 200);
	assert.equal(response.headers.get("cache-control"), "no-store");
	const body = await response.json();

	assert.equal(body.melbourne_today, today);
	assert.deepEqual(body.today, expectedPeriod(today));
	assert.deepEqual(body.this_week, expectedPeriod(weekStart));
	assert.deepEqual(body.this_month, expectedPeriod(monthStart));

	// All-time totals are fixed by the fixture amounts: the cancelled order is
	// never included, and only the Picked Up order is collected.
	assert.deepEqual(body.all_time, { sales: "177.00", orders: 5, collected: "25.00" });
	assert.equal(body.today.collected, "25.00");
	assert.equal(body.this_week.collected, "25.00");
	assert.equal(body.this_month.collected, "25.00");
	assert.equal(body.all_time.collected, "25.00");

	for (const period of ["today", "this_week", "this_month", "all_time"]) {
		assert.match(body[period].sales, /^\d+\.\d{2}$/, `${period} sales must be money with two decimals`);
		assert.match(body[period].collected, /^\d+\.\d{2}$/, `${period} collected must be money with two decimals`);
		assert.equal(typeof body[period].orders, "number");
	}

	// 14 days, oldest first, ending with today, with explicit zeros.
	const expectedDaily = [];
	for (let offset = 0; offset < 14; offset += 1) {
		const date = addDays(dailyStart, offset);
		const sales = fixtures
			.filter(fixture => fixture.status !== "Cancelled" && fixture.melbourneDate === date)
			.reduce((sum, fixture) => sum + fixture.total, 0);
		expectedDaily.push({ date, sales: money(sales) });
	}
	assert.equal(body.daily.length, 14);
	assert.equal(body.daily[0].date, dailyStart);
	assert.equal(body.daily[13].date, today);
	assert.deepEqual(body.daily, expectedDaily);
	assert.ok(body.daily.some(day => day.sales === "0.00"), "days without orders must be zero-filled");
	for (const day of body.daily) {
		assert.match(day.sales, /^\d+\.\d{2}$/, "daily sales must be money with two decimals");
	}

	// The order detail is additive: the new fields are present there...
	const detail = await ownerRequest(server, session, "GET", `/api/owner/orders/${ids.today}`);
	assert.equal(detail.status, 200);
	assert.equal(detail.headers.get("cache-control"), "no-store");
	const detailBody = await detail.json();
	assert.equal(detailBody.customer_email, "today@example.com");
	assert.ok(Object.hasOwn(detailBody, "created_at"), "created_at must be returned");
	assert.notEqual(detailBody.created_at, null);
	assert.equal(detailBody.subtotal, "13.00");
	assert.equal(detailBody.discount, "2.00");
	assert.equal(detailBody.shipping_fee, "1.00");
	assert.equal(detailBody.total, "12.00");
	assert.equal(detailBody.order_number, `MS-${ids.today}`);

	// ...and are not added to the list endpoint.
	const list = await ownerRequest(server, session, "GET", "/api/owner/orders");
	assert.equal(list.status, 200);
	const listed = (await list.json()).find(order => order.id === String(ids.today));
	assert.ok(listed, "the seeded order must be listed");
	assert.equal(listed.customer_email, undefined);
	assert.equal(listed.subtotal, undefined);
	assert.equal(listed.discount, undefined);
	assert.equal(listed.shipping_fee, undefined);
});
